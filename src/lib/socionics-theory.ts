/** Чи тема вікторини «покрита» пройденими уроками */
export function topicCovered(
  topic: Exclude<Topic, 'full'> | 'full',
  done: Partial<Record<LessonId, boolean>>,
): boolean {
  const ids = topic === 'full' ? ALL_LESSONS_FOR_FULL : TOPIC_LESSONS[topic]
  return ids.every((id) => done[id])
}

