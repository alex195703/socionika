import type { Bi } from './i18n'
import { ukAbbr } from './socionics-data'
import type { Topic } from './socionics-quiz'

const A = (s: string): string => ukAbbr(s)
/** Абревіатура двомовно: uk — ІЛЕ, ru — ИЛЭ */
const ab = (s: string): Bi => ({ uk: A(s), ru: s })

export type LessonId = 'l1' | 'l2' | 'l3' | 'l4' | 'l5' | 'l6'

export interface Checkpoint {
  id: string
  q: Bi
  options: Bi[]
  correct: number // індекс у options
  why: Bi         // пояснення після відповіді
}

export type LessonBlock =
  | { kind: 'p'; text: Bi }                       // абзац
  | { kind: 'h'; text: Bi }                       // підзаголовок
  | { kind: 'list'; items: Bi[] }                 // маркований список
  | { kind: 'table'; head: Bi[]; rows: Bi[][] }   // таблиця
  | { kind: 'example'; text: Bi }                 // приклад у рамці
  | { kind: 'check'; cp: Checkpoint }             // міні-перевірка

export interface Lesson {
  id: LessonId
  topic: Exclude<Topic, 'full'> // яка тема вікторини перевіряє цей урок
  title: Bi
  subtitle: Bi
  minutes: number
  blocks: LessonBlock[]
}

